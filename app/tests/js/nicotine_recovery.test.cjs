const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname,'../../templates/tvw_guided_mix_session.html'),'utf8');
const functions = source.slice(source.indexOf('  const renderNicotineRecoveryProgressNote ='),source.indexOf('  const isLargeUnderClassification'));
const box = {classList:{remove(){}}};
const context = {guidedPolicyBox:box,escHtml:s=>s};
vm.createContext(context);
vm.runInContext('let nicotineRecoveryUi = null;\n'+functions+'\nthis.api={enterNicotineRecovery,syncNicotineRecoveryUiFromReading,renderNicotineRecoveryProgressNote,get:()=>nicotineRecoveryUi};',context);
const api=context.api;
api.enterNicotineRecovery(3,{}, {},{nicotine_recovery_mode:true,nicotine_residue_reading_required:true,display_target_grams:0.31});
assert.equal(api.get().measured,null);
assert.equal(api.get().mode,'recovery_check');
api.renderNicotineRecoveryProgressNote('Nicotine recovery',0.31,null,null,'Enter current reading');
assert.match(box.innerHTML,/Current scale: —/);
assert.match(box.innerHTML,/Needed: —/);
assert.match(box.innerHTML,/Do not tare/);
api.syncNicotineRecoveryUiFromReading(3,{reading:{recovery_current_scale_grams:0.08},session:{steps:[{step_no:3,payload:{nicotine_recovery_mode:true,recovery_current_scale_grams:0.08}}]}});
api.syncNicotineRecoveryUiFromReading(3,{reading:{recovery_current_scale_grams:0},session:{steps:[{step_no:3,payload:{nicotine_recovery_mode:true,recovery_current_scale_grams:0,measured_grams:0}}]}});
assert.equal(api.get().measured,0);
api.enterNicotineRecovery(3,{}, {measured_grams:0},{nicotine_recovery_mode:true,recovery_current_scale_grams:0,measured_grams:0,display_target_grams:0.31});
assert.equal(api.get().measured,0);
api.renderNicotineRecoveryProgressNote('Nicotine recovery',0.31,0,0.31,'Continue to original target');
assert.match(box.innerHTML,/Current scale: 0.00 g/);
assert.match(box.innerHTML,/Needed: 0.31 g/);
api.enterNicotineRecovery(3,{}, {},{nicotine_accept_confirm_pending:true,measured_grams:0.35,display_target_grams:0.31});
assert.equal(api.get().mode,'pour_back');
console.log('Nicotine recovery UI regressions passed');
