PRAGMA foreign_keys = ON;

-- 1. USERS & SECURITY
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL, -- 'Master', 'Old Goat', 'Foreman', 'Mixer', 'Hand', 'Kid'
    status TEXT DEFAULT 'Active',
    last_login DATETIME
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    actor_id INTEGER, 
    action TEXT,         
    target_table TEXT,  
    target_id INTEGER, 
    details TEXT, 
    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(actor_id) REFERENCES users(id)
);

-- 2. MASTER CATALOG (The "Brain" for Grams-to-ML)
CREATE TABLE IF NOT EXISTS flavor_reference (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    brand TEXT NOT NULL,
    name TEXT NOT NULL,
    category TEXT DEFAULT 'Flavor', -- 'Flavor', 'Base', 'Nicotine'
    profiles TEXT, -- Comma-separated tags
    price_10ml REAL DEFAULT 0.0,
    price_per_ml REAL DEFAULT 0.0,
    
    -- Critical for Precision Engine
    density REAL DEFAULT 1.036, -- Density (g/ml)
    is_nicotine INTEGER DEFAULT 0, -- Safety Tagging (0 or 1)
    
    -- Flavor Metadata
    avg_usage REAL DEFAULT 0.0, 
    min_percent REAL DEFAULT 0.0,
    max_percent REAL DEFAULT 0.0,
    
    url TEXT,
    source TEXT DEFAULT 'Manual',
    active INTEGER DEFAULT 1,
    last_scraped DATETIME DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(brand, name) 
);

-- 3. THE PHYSICAL INVENTORY (What's on the shelf)
CREATE TABLE IF NOT EXISTS library_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    reference_id INTEGER,
    current_stock REAL DEFAULT 0, -- Measured in ML (calculated from Poured Grams)
    low_stock_threshold REAL DEFAULT 10.0,
    cost_per_unit REAL DEFAULT 0, 
    unit TEXT DEFAULT 'ml', 
    
    -- Nicotine Specific (Stored here for inventory management)
    nic_strength REAL DEFAULT 0.0, 
    nic_type TEXT, -- 'Salt', 'Freebase'
    nic_base_ratio TEXT, -- '100% VG', '50/50'
    
    notes TEXT,
    active INTEGER DEFAULT 1,
    status TEXT DEFAULT 'In Use', -- Added to match inventory.py logic ('In Use', 'Empty')
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(reference_id) REFERENCES flavor_reference(id) ON DELETE CASCADE
);

-- GLOBAL BULK STOCK (VG/PG Drums)
CREATE TABLE IF NOT EXISTS global_stock (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT UNIQUE NOT NULL, -- 'VG', 'PG'
    category TEXT DEFAULT 'Base',
    current_stock REAL DEFAULT 0,
    unit TEXT DEFAULT 'g',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 4. RECIPES & VERSIONS
CREATE TABLE IF NOT EXISTS recipes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    recipe_code TEXT UNIQUE,
    status TEXT DEFAULT 'Experimental', 
    created_by INTEGER,
    active INTEGER DEFAULT 1,
    FOREIGN KEY(created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS recipe_versions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    recipe_id INTEGER,
    version_number TEXT NOT NULL, 
    target_vg_pg_ratio TEXT DEFAULT '70/30',
    total_flavor_percent REAL,
    notes TEXT,
    is_locked INTEGER DEFAULT 0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(recipe_id) REFERENCES recipes(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS recipe_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    version_id INTEGER,
    ingredient_id INTEGER, -- Links to flavor_reference
    amount_percent REAL NOT NULL,
    FOREIGN KEY(version_id) REFERENCES recipe_versions(id) ON DELETE CASCADE,
    FOREIGN KEY(ingredient_id) REFERENCES flavor_reference(id)
);

-- 5. BATCH PRODUCTION & HISTORY
-- Note: Reconciled with inventory.py (mix_history / batch_ingredients)
CREATE TABLE IF NOT EXISTS mix_history (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_number TEXT UNIQUE, -- Can be NULL or Autogenerated if not provided
    recipe_id INTEGER,
    version_id INTEGER,
    user_id INTEGER,
    supervisor_id INTEGER,
    total_volume_actual REAL,
    total_weight_actual REAL, 
    session_token TEXT UNIQUE,
    style TEXT,
    mix_mode TEXT,
    vessel_size REAL,
    safety_json TEXT,
    ready_for_sale INTEGER DEFAULT 0,
    total_cost REAL DEFAULT 0.0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(recipe_id) REFERENCES recipes(id),
    FOREIGN KEY(version_id) REFERENCES recipe_versions(id),
    FOREIGN KEY(user_id) REFERENCES users(id),
    FOREIGN KEY(supervisor_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS mix_history_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id INTEGER NOT NULL,
    ingredient_id INTEGER NOT NULL, -- flavor_reference.id, or 0=PG, -1=VG
    measured_grams REAL NOT NULL,
    target_grams REAL,
    delta_grams REAL,
    cost_at_time REAL DEFAULT 0.0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(batch_id) REFERENCES mix_history(id) ON DELETE CASCADE
);

-- Renamed to batch_ingredients to perfectly match your deduction script
CREATE TABLE IF NOT EXISTS batch_ingredients (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id INTEGER,
    reference_id INTEGER, 
    target_grams REAL,
    actual_grams REAL, -- Renamed from measured_grams for consistency
    variance REAL, 
    cost_at_time REAL, 
    FOREIGN KEY(batch_id) REFERENCES mix_history(id) ON DELETE CASCADE,
    FOREIGN KEY(reference_id) REFERENCES flavor_reference(id)
);

-- 6. PERFORMANCE INDEXES
CREATE INDEX IF NOT EXISTS idx_ref_lookup ON flavor_reference(brand, name);
CREATE INDEX IF NOT EXISTS idx_ref_nic ON flavor_reference(is_nicotine);
CREATE INDEX IF NOT EXISTS idx_lib_ref_active ON library_items(reference_id, active);
CREATE INDEX IF NOT EXISTS idx_recipe_lookup ON recipes(recipe_code);
CREATE INDEX IF NOT EXISTS idx_batch_num ON mix_history(batch_number);